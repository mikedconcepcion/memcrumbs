"""CLI v1 argument parser (frozen under semver from 1.0; see docs/cli.md)."""
import argparse

# commands that run without a configured project
NO_PROJECT = ("init", "template", "outline", "scan")


def build_parser(extra=None, errors=None):
    ap = argparse.ArgumentParser(prog="memcrumbs", description="memcrumbs: project wiki + token-efficient index")
    ap.add_argument("-p", "--project", help="project name (default: from cwd)")
    ap.add_argument("--version", action="store_true", help="print the version")
    sp = ap.add_subparsers(dest="cmd")
    common = argparse.ArgumentParser(add_help=False)     # accepted after the subcommand too
    common.add_argument("-p", "--project", default=argparse.SUPPRESS, help=argparse.SUPPRESS)
    common.add_argument("--json", action="store_true", help="one JSON object instead of text")
    common.add_argument("--full", action="store_true", help="lift the output cap (index: re-parse every file)")

    def add(name, **kw):
        return sp.add_parser(name, parents=[common], **kw)

    s = add("find", help="search the wiki, docs and code; ranked hits with path:line, age and status")
    s.add_argument("query", nargs="+")
    s.add_argument("-k", "--kind", help="comma list: wiki (all wiki kinds), runbook, decision, incident, journal, "
                                        "doc, research, memory, code, bug, legacy, log")
    s.add_argument("-n", type=int, default=8)
    s.add_argument("--explain", action="store_true", help="show how the query was read: terms, synonyms, intent")
    s = add("page", help="a wiki page (a table of contents if long) or one section")
    s.add_argument("name")
    s.add_argument("section", nargs="?")
    s = add("outline", help="symbols + line ranges of a code/markdown file (or list a folder)")
    s.add_argument("path")
    s.add_argument("--kinds", help="e.g. def,class or input")
    s.add_argument("--grep")
    s.add_argument("--depth", type=int, default=9)
    s = add("fact", help="a registered current value with its source and age (wiki/facts.md); no key lists all")
    s.add_argument("key", nargs="?")
    s = add("about", help="what the wiki records about a file: decisions with verdicts, incidents, gotchas")
    s.add_argument("path")
    s = add("sym", help="where a function/class/input is defined")
    s.add_argument("name")
    s.add_argument("--in", dest="path_like")
    s.add_argument("--body", action="store_true", help="print the first match's source")
    s.add_argument("-n", type=int, default=10)
    s = add("log", help="append a dated line to the wiki journal")
    s.add_argument("text", nargs="+")
    s.add_argument("--tag")
    s = add("decision", help="capture a decision or research verdict with a status")
    s.add_argument("title")
    s.add_argument("--status", required=True, choices=("accepted", "rejected", "parked", "superseded"))
    s.add_argument("--why", default="")
    s.add_argument("--tag", action="append", default=[])
    s.add_argument("--considered", default="", help="the options weighed, separated by ';'")
    s.add_argument("--evidence", default="", help="the numbers behind the verdict, and where they came from")
    s.add_argument("--revisit-if", default="", help="what would reopen this decision")
    s = add("incident", help="capture an incident: what you saw, root cause, fix, the guard against a repeat")
    s.add_argument("title")
    s.add_argument("--cause", default="")
    s.add_argument("--fix", default="")
    s.add_argument("--tag", action="append", default=[])
    s.add_argument("--symptom", default="", help="what someone sees first, in their words (searched like the title)")
    s.add_argument("--guard", default="", help="the check or rule that stops it recurring")
    s.add_argument("--lucky", default="", help="where we got lucky (optional)")
    s = add("verify", help="set a page's verified date (after re-checking its facts)")
    s.add_argument("page")
    s.add_argument("--date", help="YYYY-MM-DD (default today)")
    s = add("suggest", help="offers with evidence: duplicates, missing links, big pages, guards, gaps; apply on a yes")
    s.add_argument("action", nargs="?", choices=("show", "apply", "undo", "dismiss"))
    s.add_argument("id", nargs="?")
    s.add_argument("--kind", help="comma list of kinds (list), or the kind to apply as a batch")
    s.add_argument("--for", dest="period", help="dismiss for a period, e.g. 14d (default 14d)")
    s.add_argument("--never", action="store_true", help="dismiss for good")
    s.add_argument("--outside-wiki", action="store_true", help="apply a patch that writes outside the wiki")
    s.add_argument("--allow-destructive", action="store_true", help="apply a destructive patch")
    s.add_argument("--name", help="skill suggestions: the skill's name")
    s.add_argument("--owner-only", action="store_true", help="skill suggestions: only the owner can start it")
    s.add_argument("--agent-may-use", action="store_true", help="skill suggestions: the agent may start it too")
    s.add_argument("--deny", action="store_true",
                   help="guard suggestions: refuse the command instead of asking (the owner's choice)")
    s = add("rule", help="add a standing rule to rules.md ## Top (it waits for the owner's review)")
    s.add_argument("text", nargs="+")
    s = add("review", help="what waits for the owner's review: new header lines, agent-written pages")
    s.add_argument("--approve", metavar="IDS", help="all, kept, or ids from the list (refused inside an agent shell)")
    s.add_argument("--kept", action="store_true", help="list the header lines kept without review at the upgrade")
    s = add("quarantine", help="keep a page on disk but out of the index and the header")
    s.add_argument("page")
    s.add_argument("--lift", action="store_true", help="put it back (refused inside an agent shell)")
    s = add("supersede", help="mark a page superseded (it ranks below current pages)")
    s.add_argument("page")
    s.add_argument("--by", help="the page that replaces it")
    s = add("check", help="lint the wiki (+ plugin checks); exit 1 on errors")
    s.add_argument("--baseline", action="store_true", help="record today's findings; later runs list only new ones")
    s.add_argument("--all", action="store_true", help="list baselined findings too")
    s.add_argument("--strict", action="store_true", help="exit 1 on new warnings as well")
    s.add_argument("--dupes", action="store_true", help="also list near-duplicate pages")
    s = add("scan", help="secret-scan a folder, file, sdist or wheel; exit 1 on hits")
    s.add_argument("path", nargs="?", default=".")
    s = add("status", help="the session header")
    s.add_argument("--hook", action="store_true", help="SessionStart mode: never fails, never blocks")
    add("index", help="refresh the index (--full re-parses every file)")
    s = add("stats", help="index counts")
    s.add_argument("--usage", action="store_true", help="output size and latency per command (no content logged)")
    s = add("bench", help="recall@k, tokens and latency on a question file (default: wiki/bench.toml)")
    s.add_argument("questions", nargs="?")
    s.add_argument("--min-recall3", type=float, help="exit 1 if recall@3 is below this")
    s.add_argument("-k", type=int, default=8, help="hits per question")
    s.add_argument("--add", metavar="QUESTION", help="record a question the wiki should answer (wiki/bench.toml)")
    s.add_argument("--expect", action="append", default=[], help="with --add: the page or file that answers it")
    s.add_argument("--category", default="", help="with --add")
    s = add("plan", help="wiki refresh plan: what needs an agent, why, est. tokens; approve with a budget")
    s.add_argument("action", nargs="?", choices=("next",), help="next: the next approved page (for the agent)")
    s.add_argument("--approve", metavar="PAGES", help="comma list of pages, top:N or all")
    s.add_argument("--budget", type=int, help="est. token budget for the approved refresh")
    s.add_argument("--clear", action="store_true", help="forget approvals")
    s = add("dashboard", help="write a static HTML dashboard (health, freshness, usage, refresh control)")
    s.add_argument("--open", action="store_true", help="open it in the browser")
    s = add("doctor", help="check the install, config, plugins, index and the wired hook")
    s.add_argument("--share", action="store_true", help="a content-free summary that is safe to share")
    add("template", help="print the wiki page skeleton")
    add("secret-add", help="add a secret to the redaction list (stored only as a sha256 hash)")
    s = add("init", help="create a project")
    s.add_argument("name")
    s.add_argument("--repo", action="append", default=[])
    s.add_argument("--title")
    s = add("wire", help="connect a repo to an agent (dry run unless --apply)")
    s.add_argument("--repo")
    s.add_argument("--target", default="claude", help="comma list: claude, agents")
    s.add_argument("--apply", action="store_true")
    s.add_argument("--remove", action="store_true", help="take out exactly what wire added")
    s.add_argument("--user-skill", action="store_true", help="the skill goes to ~/.claude/skills")
    s.add_argument("--allow", action="store_true", help="allow the read-only lookups (find, page, outline, sym, "
                                                         "status) without approval, for Bash and PowerShell")
    for name, (setup, _, hlp) in (extra or {}).items():
        if name not in sp.choices:
            try:
                setup(add(name, help=hlp))
            except Exception as e:                     # a plugin command that cannot be set up is skipped
                sp.choices.pop(name, None)
                if errors is not None:
                    errors.append(("command %s" % name, "%s: %s" % (type(e).__name__, str(e)[:120])))
    return ap
